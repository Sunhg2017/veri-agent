export function dictionaryLabel(value: unknown, fallback = '-') {
  if (value === undefined || value === null || value === '') {
    return fallback;
  }
  const raw = String(value).trim();
  return resolveValueLabel(raw) ?? humanizeDictionaryValue(raw);
}

export function displayValueLabel(value: unknown, fallback = '-') {
  if (value === undefined || value === null || value === '') {
    return fallback;
  }
  const raw = String(value).trim();
  return resolveValueLabel(raw) ?? (looksLikeEnumValue(raw) ? humanizeDictionaryValue(raw) : raw);
}

export function fieldLabel(value: unknown, fallback = '-') {
  if (value === undefined || value === null || value === '') {
    return fallback;
  }
  const raw = String(value).trim();
  const normalized = normalizeFieldLabelKey(raw);
  const labelKey = labelKeys[normalizeDictionaryKey(raw)];
  return fieldLabels[raw] ?? fieldLabels[normalized] ?? (labelKey ? translate(labelKey) : dictionaryLabel(raw, fallback));
}

export function dictionaryOption<T extends string>(value: T, disabled = false): DictionaryOption<T> {
  return {
    disabled,
    label: dictionaryLabel(value),
    value
  };
}

export function dictionaryOptions<T extends string>(values: readonly T[]): Array<DictionaryOption<T>> {
  return values.map((value) => dictionaryOption(value));
}

export function dictionaryListLabel(value: unknown, fallback = '-') {
  if (value === undefined || value === null || value === '') {
    return fallback;
  }
  const items = String(value)
    .split(',')
    .map((item) => item.trim())
    .filter(Boolean);
  if (!items.length) {
    return fallback;
  }
  return items.map((item) => dictionaryLabel(item)).join('、');
}

export function humanizeDictionaryValue(value: string) {
  if (/^[A-Z0-9]{2,8}$/.test(value)) {
    return value;
  }
  return value
    .split(/[_\s-]+/)
    .filter(Boolean)
    .map((part) => part.length <= 3 ? part.toUpperCase() : `${part.charAt(0).toUpperCase()}${part.slice(1).toLowerCase()}`)
    .join(' ');
}

function normalizeDictionaryKey(value: string) {
  return value.trim().replace(/[-\s]+/g, '_').toUpperCase();
}

function resolveValueLabel(value: string) {
  const key = normalizeDictionaryKey(value);
  const labelKey = labelKeys[key];
  return valueLabels[key] ?? (labelKey ? translate(labelKey) : undefined);
}

function looksLikeEnumValue(value: string) {
  return /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$/.test(value);
}

function normalizeFieldLabelKey(value: string) {
  const words = value
    .trim()
    .replace(/JSON\b/g, 'Json')
    .replace(/ID\b/g, 'Id')
    .split(/[\s_-]+/)
    .filter(Boolean);
  const joined = words.join('');
  const directCamel = joined ? `${joined.charAt(0).toLowerCase()}${joined.slice(1)}` : '';
  if (directCamel && /[a-z][A-Z]/.test(directCamel)) {
    return directCamel;
  }
  if (joined && joined === joined.toUpperCase()) {
    return joined.toLowerCase();
  }
  return words
    .map((word, index) => {
      const normalized = index === 0 ? `${word.charAt(0).toLowerCase()}${word.slice(1)}` : `${word.charAt(0).toUpperCase()}${word.slice(1)}`;
      return index === 0 ? normalized : `${normalized.charAt(0).toUpperCase()}${normalized.slice(1)}`;
    })
    .join('');
}
